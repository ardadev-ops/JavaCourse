public class GalToLit {
    /*
    Try this 1-1
    This program converts gallons to liters.
    GalToLit
     */
    public static void run() {
        double gallons;
        double liters;
        gallons = 10; //start with 10
        liters = gallons * 3.7854; //Convert to liters
        System.out.println(gallons + " gallons is " + liters + " liters.");

    }
}
